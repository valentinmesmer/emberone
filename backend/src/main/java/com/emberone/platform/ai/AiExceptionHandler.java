package com.emberone.platform.ai;

import java.util.Map;
import lombok.extern.slf4j.Slf4j;
import org.springframework.core.annotation.Order;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;

/**
 * Maps AI-specific failures to the canonical {@code {"error": ...}} body. Handles only the two
 * exception types below; everything else (including {@link AiUnavailableException}, a {@code
 * ConflictException}) stays with the existing handlers.
 */
@Slf4j
@Order(0)
@RestControllerAdvice
public class AiExceptionHandler {

    @ExceptionHandler(AiProviderException.class)
    public ResponseEntity<Map<String, String>> handleProvider(AiProviderException ex) {
        // Message is generated by our code and never contains prompt or answer content.
        log.warn("AI provider error: {}", ex.getMessage());
        return error(HttpStatus.BAD_GATEWAY, "The AI service is temporarily unavailable.");
    }

    @ExceptionHandler(AiRateLimitException.class)
    public ResponseEntity<Map<String, String>> handleRateLimit(AiRateLimitException ex) {
        return error(HttpStatus.TOO_MANY_REQUESTS, ex.getMessage());
    }

    private static ResponseEntity<Map<String, String>> error(HttpStatus status, String message) {
        return ResponseEntity.status(status).body(Map.of("error", message));
    }
}
