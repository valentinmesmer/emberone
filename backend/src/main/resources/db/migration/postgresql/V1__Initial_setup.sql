    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NULL,
    bucket_name TEXT NOT NULL,
    object_key TEXT,
    key_prefix TEXT,
    status VARCHAR(16) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    last_error TEXT,
    next_attempt_at TIMESTAMPTZ NULL DEFAULT now(),
    processing_started_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_obj_pending_deletions_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE SET NULL,
    CONSTRAINT chk_obj_pending_deletions_target CHECK (
        (object_key IS NOT NULL AND key_prefix IS NULL)
        OR (object_key IS NULL AND key_prefix IS NOT NULL)
    )
);

CREATE INDEX idx_obj_pending_deletions_pending
    ON obj_pending_deletions (tenant_id, status, next_attempt_at) WHERE status = 'PENDING';

