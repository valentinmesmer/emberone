-- ============================================================
-- Action log (append-only audit trail)
-- New auditable tables: attach AFTER INSERT OR UPDATE OR DELETE ... EXECUTE FUNCTION emberone_action_log();
-- ============================================================

CREATE TABLE action_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id       BIGINT NOT NULL,
    table_name      TEXT NOT NULL,
    record_id       BIGINT NOT NULL,
    action          TEXT NOT NULL CHECK (action IN ('CREATE', 'UPDATE', 'DELETE')),
    user_id         BIGINT,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_columns TEXT[],
    CONSTRAINT fk_action_log_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    PRIMARY KEY (id, changed_at)
) PARTITION BY RANGE (changed_at);

DO $$
DECLARE
    partition_start DATE := DATE '2026-01-01';
    partition_end   DATE;
    partition_name  TEXT;
BEGIN
    WHILE partition_start < DATE '2032-01-01' LOOP
        partition_end := (partition_start + INTERVAL '1 month')::DATE;
        partition_name := 'action_log_' || to_char(partition_start, 'YYYY_MM');
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF action_log FOR VALUES FROM (%L) TO (%L)',
            partition_name,
            partition_start,
            partition_end
        );
        partition_start := partition_end;
    END LOOP;
END $$;

