CREATE TABLE appointment_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    recurrence_rule VARCHAR(512) NOT NULL,
    series_start TIMESTAMPTZ NOT NULL,
    series_end TIMESTAMPTZ NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Europe/Berlin',
    name VARCHAR(255) NOT NULL,
    type VARCHAR(64) NOT NULL,
    location VARCHAR(512) NULL,
    description TEXT NULL,
    response_mode VARCHAR(64) NOT NULL,
    response_deadline_minutes_before INT NOT NULL DEFAULT 0,
    audience_scope VARCHAR(64) NOT NULL,
    CONSTRAINT uk_appointment_series_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_appointment_series_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    series_id BIGINT NULL,
    occurrence_start TIMESTAMPTZ NOT NULL,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(64) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    location VARCHAR(512) NULL,
    description TEXT NULL,
    response_mode VARCHAR(64) NOT NULL,
    response_deadline_minutes_before INT NOT NULL DEFAULT 0,
    audience_scope VARCHAR(64) NOT NULL,
    is_exception BOOLEAN NOT NULL DEFAULT FALSE,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    archived_at TIMESTAMPTZ NULL,
    CONSTRAINT chk_appointments_retirement CHECK (
        (archived AND archived_at IS NOT NULL) OR (NOT archived AND archived_at IS NULL)
    ),
    CONSTRAINT fk_appointments_series FOREIGN KEY (series_id) REFERENCES appointment_series (id) ON DELETE SET NULL,
    CONSTRAINT uk_appointments_series_occurrence UNIQUE (tenant_id, series_id, occurrence_start),
    CONSTRAINT uk_appointments_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_appointments_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE
);

CREATE TABLE appointment_audience_groups (
    tenant_id BIGINT NOT NULL,
    appointment_id BIGINT NOT NULL,
    organization_group_id BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, appointment_id, organization_group_id),
    CONSTRAINT fk_appointment_audience_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_appointment_audience_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE
