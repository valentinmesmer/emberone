CREATE OR REPLACE FUNCTION emberone_action_log()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_tenant_id BIGINT;
  v_user_id   BIGINT;
  v_record_id BIGINT;
  v_action    TEXT;
  v_row       JSONB;
  v_changed_columns TEXT[];
BEGIN
  IF current_setting('app.purging', true) = 'true'
     OR current_setting('app.retention', true) = 'true' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  v_tenant_id := NULLIF(current_setting('app.tenant_id', true), '')::BIGINT;
  v_user_id   := NULLIF(current_setting('app.user_id', true), '')::BIGINT;

  IF TG_OP = 'INSERT' THEN
    v_action := 'CREATE';
    v_row := to_jsonb(NEW);
  ELSIF TG_OP = 'UPDATE' THEN
    v_action := 'UPDATE';
    SELECT COALESCE(array_agg(key ORDER BY key), ARRAY[]::TEXT[])
    INTO v_changed_columns
    FROM (
      SELECT o.key, o.value AS old_val, n.value AS new_val
      FROM jsonb_each(to_jsonb(OLD)) AS o(key, value)
      FULL OUTER JOIN jsonb_each(to_jsonb(NEW)) AS n(key, value) ON o.key = n.key
      WHERE o.value IS DISTINCT FROM n.value
    ) changed;
    IF v_changed_columns IS NULL OR cardinality(v_changed_columns) = 0 THEN
      RETURN NEW;
    END IF;
    v_row := to_jsonb(NEW);
  ELSE
    v_action := 'DELETE';
    v_row := to_jsonb(OLD);
  END IF;

  v_record_id := COALESCE(
    (v_row->>'id')::BIGINT,
    (v_row->>'template_id')::BIGINT,
    (v_row->>'standard_id')::BIGINT,
    (v_row->>'tenant_id')::BIGINT
  );
  v_tenant_id := COALESCE(v_tenant_id, (v_row->>'tenant_id')::BIGINT);
  IF TG_TABLE_NAME = 'tenants' THEN
    v_tenant_id := COALESCE(v_tenant_id, v_record_id);
  END IF;
  IF TG_TABLE_NAME = 'idm_users' THEN
    v_record_id := COALESCE((v_row->>'emberone_user_id')::BIGINT, v_record_id);
  END IF;

  INSERT INTO action_log (tenant_id, table_name, record_id, action, user_id, changed_columns)
  VALUES (v_tenant_id, TG_TABLE_NAME, v_record_id, v_action, v_user_id, v_changed_columns);

  RETURN COALESCE(NEW, OLD);
END;
$$;

