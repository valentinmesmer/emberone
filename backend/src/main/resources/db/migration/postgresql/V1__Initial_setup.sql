-- Greenfield PostgreSQL schema: multi-tenant baseline, appointment reads, action log.

CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    abbreviation VARCHAR(32) NOT NULL,
    locale VARCHAR(10) NOT NULL DEFAULT 'de',
    federal_state VARCHAR(32) NOT NULL,
    CONSTRAINT uq_tenants_abbreviation UNIQUE (abbreviation)
);

-- Cluster-wide scheduler locks (ShedLock, not tenant-scoped)
CREATE TABLE shedlock (
    name VARCHAR(64) NOT NULL PRIMARY KEY,
    lock_until TIMESTAMPTZ NOT NULL,
    locked_at TIMESTAMPTZ NOT NULL,
    locked_by VARCHAR(255) NOT NULL
);

CREATE TABLE tenant_personal_number_sequences (
    tenant_id BIGINT PRIMARY KEY,
    next_personal_number BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT fk_tenant_personal_number_sequences_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE
);

CREATE TABLE organization_type_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    config_key VARCHAR(255) NULL,
    name VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_organization_type_definitions_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE
);

CREATE INDEX idx_organization_type_definitions_tenant ON organization_type_definitions (tenant_id);

CREATE UNIQUE INDEX uk_organization_type_definitions_config_key
    ON organization_type_definitions (tenant_id, config_key)
    WHERE config_key IS NOT NULL;

ALTER TABLE organization_type_definitions ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_type_definitions_tenant_policy ON organization_type_definitions
    USING (tenant_id = (SELECT NULLIF(current_setting('app.tenant_id', true), '')::BIGINT));

ALTER TABLE organization_type_definitions FORCE ROW LEVEL SECURITY;

CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_code VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    organization_type_id BIGINT NOT NULL,
    parent_organization_id BIGINT NULL,
    standard_id BIGINT NULL,
    deactivated_at TIMESTAMPTZ NULL,
    CONSTRAINT uk_organizations_code UNIQUE (tenant_id, organization_code),
    CONSTRAINT uk_organizations_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_organizations_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_organizations_type FOREIGN KEY (organization_type_id) REFERENCES organization_type_definitions(id)
);

CREATE INDEX idx_organizations_parent ON organizations (tenant_id, parent_organization_id);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    personal_number BIGINT NOT NULL,
    salutation VARCHAR(255) NULL,
    username VARCHAR(255) NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    date_of_birth DATE NULL,
    deactivated_at TIMESTAMPTZ NULL,
    CONSTRAINT uk_users_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uk_users_tenant_personal_number UNIQUE (tenant_id, personal_number),
    CONSTRAINT uk_users_tenant_username UNIQUE (tenant_id, username),
    CONSTRAINT fk_users_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE
);

CREATE TABLE organization_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT NULL,
    type VARCHAR(50) NOT NULL DEFAULT 'CUSTOM',
    config_key VARCHAR(255) NULL,
    standard_origin_id BIGINT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    archived_at TIMESTAMPTZ NULL,
    CONSTRAINT chk_organization_groups_retirement CHECK (
        (archived AND archived_at IS NOT NULL) OR (NOT archived AND archived_at IS NULL)
    ),
    CONSTRAINT uk_org_groups_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_org_groups_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE
);

CREATE TABLE user_organization_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    main BOOLEAN NOT NULL DEFAULT FALSE,
